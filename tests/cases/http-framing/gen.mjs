// Makes cases.ab (requests.mjs as Abla string literals plus the loop that frames them) for tools/test-http-framing.sh:
//   node gen.mjs <cases.ab>
import { writeFileSync } from "node:fs";
import { requests } from "./requests.mjs";
const enc = (s) => { let o = ""; for (const ch of s) { const x = ch.charCodeAt(0); o += (x >= 32 && x < 127 && x !== 34 && x !== 92 && x !== 36) ? ch : "\\x" + x.toString(16).padStart(2, "0"); } return o; };
let src = `// Generated by gen.mjs: do not edit.\nimport "abla/io"\nimport "abla/http"\nimport "abla/http/event"\n\nfun names(): array<string> = [\n${requests.map(([n]) => `    "${n}",`).join("\n")}\n]\n\nfun streams(): array<string> = [\n${requests.map(([, raw]) => `    "${enc(raw)}",`).join("\n")}\n]\n\n`;
src += `fun hexOf(s: string): string {
    if (s.size == 0) return "-"
    var out = ""
    for (b in s) out = out + "0123456789abcdef".slice(b / 16, b / 16 + 1) + "0123456789abcdef".slice(b % 16, b % 16 + 1)
    out
}

// What the event server does with the bytes it has read: frame a request, hand it over, frame the rest.
fun verdict(stream: string): string {
    var input = stream
    var out = ""
    var more = true
    while (more) {
        val frame = httpEventFrame(input, 65536, 1048576)
        if (frame.length < 0) {
            out = out + (if (out == "") "" else " | ") + "E"
            more = false
        } else if (frame.length == 0 || frame.request == null) {
            more = false
        } else {
            val request = frame.request
            if (request != null) out = out + (if (out == "") "" else " | ") + "R:" + request.method + " " + request.path + " " + hexOf(request.body)
            input = input.slice(frame.length, input.size)
            if (input.size == 0) more = false
        }
    }
    if (out == "") "I" else out
}

fun cases(): array<string> {
    val out: array<string> = []
    val all = streams()
    val label = names()
    for (i in 0 until all.size) out.append(label[i] + "\\t" + verdict(all[i]))
    return out
}

fun main: int {
    val live = cases()
    val staged = #cases()
    var bad = 0
    if (live.size != staged.size) bad = 1
    for (i in 0 until (if (live.size < staged.size) live.size else staged.size)) {
        if (live[i] != staged[i]) {
            println("DIFF live: \${live[i]} | staged: \${staged[i]}")
            bad = bad + 1
        }
    }
    for (line in live) println(line)
    bad
}
`;
writeFileSync(process.argv[2], src);
