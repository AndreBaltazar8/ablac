// Writes json.ab (the inputs as Abla string literals, every byte escaped) and the verdict JSON.parse gives for each,
// for tools/test-format-edges.sh: node gen-json.mjs <json.ab> <node-verdicts.txt>
import { writeFileSync } from "node:fs";
import { inputs } from "./json-inputs.mjs";
const enc = (s) => {
    let out = "";
    for (const x of Buffer.from(s, "utf8")) out += (x >= 32 && x < 127 && x !== 34 && x !== 92 && x !== 36) ? String.fromCharCode(x) : "\\x" + x.toString(16).padStart(2, "0");
    return out;
};
let source = `// Generated by gen-json.mjs from json-inputs.mjs: do not edit.\nimport "abla/io"\nimport "abla/json"\n\nfun inputs(): array<string> = [\n`;
const verdicts = [];
for (const s of inputs) {
    source += `    "${enc(s)}",\n`;
    try { JSON.parse(s); verdicts.push("ok"); } catch { verdicts.push("err"); }
}
source += `]\n\nfun verdicts(limits: JsonLimits): array<string> {\n    val out: array<string> = []\n    for (s in inputs()) {\n        val r = jsonParse(s, limits)\n        out.append(if (r.succeeded) "ok" else "err")\n    }\n    return out\n}\n\nfun main: int {\n    for (v in verdicts(jsonPermissiveLimits)) println(v)\n    0\n}\n`;
writeFileSync(process.argv[2], source);
writeFileSync(process.argv[3], verdicts.join("\n") + "\n");
