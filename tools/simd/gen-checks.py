#!/usr/bin/env python3
"""Writes tests/cases/simd/checks.ab: every operation of abla/simd on every vector type,
each compared with a value worked out here, lane by lane, without the compiler or LLVM.
Run it after changing the surface and commit its output."""
import math
import pathlib
import random
import struct

rng = random.Random(20261031)
LANES = ["i8", "i16", "i32", "i64", "u8", "u16", "u32", "u64", "f32", "f64"]


def bits(l): return int(l[1:])
def cap(n): return n[0].upper() + n[1:]


def wrap(l, v):
    b = bits(l)
    v &= (1 << b) - 1
    if l[0] == "i" and v >= 1 << (b - 1):
        v -= 1 << b
    return v


def sat(l, v):
    b = bits(l)
    lo, hi = (-(1 << (b - 1)), (1 << (b - 1)) - 1) if l[0] == "i" else (0, (1 << b) - 1)
    return max(lo, min(hi, v))


def f32(v): return struct.unpack("<f", struct.pack("<f", v))[0]
def raw(l, v): return v & ((1 << bits(l)) - 1)


def encode(l, values):
    if l == "f32":
        return b"".join(struct.pack("<f", v) for v in values).hex()
    if l == "f64":
        return b"".join(struct.pack("<d", v) for v in values).hex()
    b = bits(l) // 8
    return b"".join(raw(l, v).to_bytes(b, "little") for v in values).hex()


def mask(l, flags): return encode(f"u{bits(l)}", [(1 << bits(l)) - 1 if f else 0 for f in flags])


def literal(l, v):
    if l == "f32" or l == "f64":
        return repr(float(v))
    if l == "u64":
        return f"u64({wrap('i64', v)})"
    if l == "i64":
        return str(v) if v != -(1 << 63) else "-9223372036854775807 - 1"
    return f"{l}({v})"


def ctor(t, l, values): return f"{t}({', '.join(literal(l, v) for v in values)})"


def samples(l, n):
    b = bits(l)
    edges = [0, 1, -1, 3, 1 << (b - 1), (1 << (b - 1)) - 1, (1 << b) - 1, 7]
    return [wrap(l, rng.choice(edges) if rng.random() < .4 else rng.getrandbits(b)) for _ in range(n)]


def fsamples(l, n):
    vals = [0.5, -0.5, 1.5, 2.25, -3.75, 100.0, 0.25, 16.0, -1.0, 4.0]
    return [rng.choice(vals) for _ in range(n)]


out = []
w = out.append
w("""// Every operation of abla/simd on every vector type, against values worked out without
// the compiler. Generated by tools/simd/gen-checks.py; change that and run it again.
import "abla/simd"
import "abla/float"

var simdFailure = 0
var simdCheck = 0

fun simdHex(bytes: string): string {
    val digits = "0123456789abcdef"
    var text = ""
    for (at in 0 until bytes.size) {
        val byte = int(bytes[at])
        text = text + digits.slice(byte >> 4, (byte >> 4) + 1) + digits.slice(byte & 15, (byte & 15) + 1)
    }
    text
}

fun simdExpect(bytes: string, hex: string): void {
    simdCheck = simdCheck + 1
    if (simdFailure == 0 && simdHex(bytes) != hex) simdFailure = simdCheck
}

fun simdTrue(value: bool): void {
    simdCheck = simdCheck + 1
    if (simdFailure == 0 && !value) simdFailure = simdCheck
}
""")

calls = []
for width in [128, 256]:
    for l in LANES:
        n = width // bits(l)
        t = f"{l}x{n}"
        m = f"u{bits(l)}"
        mt = f"{m}x{n}"
        floating = l[0] == "f"
        fn = f"simdCheck{cap(t)}"
        calls.append(fn)
        w(f"@noinline fun {fn}(): void {{")
        a = fsamples(l, n) if floating else samples(l, n)
        b = fsamples(l, n) if floating else samples(l, n)
        if floating and l == "f32":
            a = [f32(v) for v in a]
            b = [f32(v) for v in b]
        w(f"    val a = {ctor(t, l, a)}")
        w(f"    val b = {ctor(t, l, b)}")
        def e(expr, values): w(f'    simdExpect(({expr}).bytes(), "{encode(l, values)}")')
        fix = (lambda v: f32(v)) if l == "f32" else (lambda v: v) if floating else (lambda v: wrap(l, v))
        e("a", a)
        e(f"{t}Splat({literal(l, a[0])})", [a[0]] * n)
        e(f"a.with({n - 1}, {literal(l, b[0])})", a[:-1] + [b[0]])
        w(f"    simdTrue(a.get({n // 2}) == {literal(l, a[n // 2])})")
        e("a + b", [fix(x + y) for x, y in zip(a, b)])
        e("a - b", [fix(x - y) for x, y in zip(a, b)])
        e("a * b", [fix(x * y) for x, y in zip(a, b)])
        e("-a", [fix(-x) if not floating else -x for x in a])
        e("a.min(b)", [min(x, y) for x, y in zip(a, b)])
        e("a.max(b)", [max(x, y) for x, y in zip(a, b)])
        if l[0] != "u":
            e("a.abs()", [fix(abs(x)) for x in a])
        if floating:
            e("a / b", [fix(x / y) for x, y in zip(a, b)])
            s = [abs(x) for x in a]
            e(f"{ctor(t, l, s)}.sqrt()", [fix(math.sqrt(x)) for x in s])
            w(f'    simdTrue(a.toI{bits(l)}x{n}().get(0) == {literal(f"i{bits(l)}", int(a[0]))})')
            pos = [abs(x) for x in a]
            w(f'    simdExpect({ctor(t, l, pos)}.toU{bits(l)}x{n}().bytes(), "{encode(m, [int(x) for x in pos])}")')
        else:
            e("a & b", [x & y for x, y in zip(a, b)])
            e("a | b", [x | y for x, y in zip(a, b)])
            e("a ^ b", [x ^ y for x, y in zip(a, b)])
            e("~a", [~x for x in a])
            e("a.andNot(b)", [x & ~y for x, y in zip(a, b)])
            e("a.addSat(b)", [sat(l, x + y) for x, y in zip(a, b)])
            e("a.subSat(b)", [sat(l, x - y) for x, y in zip(a, b)])
            e("a << 3", [wrap(l, x << 3) for x in a])
            e("a >> 3", [x >> 3 for x in a])
            e(f"a << {bits(l)}", [0] * n)
            e(f"a >> {bits(l) + 5}", [0] * n)
            b_ = bits(l)
            rot = lambda x, k: wrap(l, (raw(l, x) << k) | (raw(l, x) >> (b_ - k)))
            e("a.rotl(3)", [rot(x, 3) for x in a])
            e("a.rotr(5)", [rot(x, b_ - 5) for x in a])
            if bits(l) >= 32:
                vals = [float(x) for x in a]
                target = f"f{bits(l)}"
                if bits(l) == 32:
                    vals = [f32(v) for v in vals]
                w(f'    simdExpect(a.toF{bits(l)}x{n}().bytes(), "{encode(target, vals)}")')
        compares = [("eq", lambda x, y: x == y), ("ne", lambda x, y: x != y), ("lt", lambda x, y: x < y),
                    ("le", lambda x, y: x <= y), ("gt", lambda x, y: x > y), ("ge", lambda x, y: x >= y)]
        for name, f in compares:
            w(f'    simdExpect(a.{name}(b).bytes(), "{mask(l, [f(x, y) for x, y in zip(a, b)])}")')
        lt = [x < y for x, y in zip(a, b)]
        e("a.lt(b).select(a, b)", [x if f else y for f, x, y in zip(lt, a, b)])
        w(f"    simdTrue(a.lt(b).bitmask() == {sum(1 << i for i, f in enumerate(lt) if f)})")
        w(f"    simdTrue(a.lt(b).any() == {'true' if any(lt) else 'false'})")
        w(f"    simdTrue(a.lt(b).all() == {'true' if all(lt) else 'false'})")
        if floating:
            w(f"    simdTrue(a.sum() == {literal(l, sum(a) if l == 'f64' else __import__('functools').reduce(lambda p, q: f32(p + q), a))})")
        else:
            w(f"    simdTrue(a.sum() == {literal(l, wrap(l, sum(a)))})")
        e("a.reverse()", a[::-1])
        e("a.interleaveLow(b)", [(a if i % 2 == 0 else b)[i // 2] for i in range(n)])
        e("a.interleaveHigh(b)", [(a if i % 2 == 0 else b)[n // 2 + i // 2] for i in range(n)])
        idx = [rng.randrange(2 * n) for _ in range(n)]
        e(f"{t}Shuffle(a, b, {', '.join(map(str, idx))})", [(a + b)[i] for i in idx])
        for other in LANES:
            if other != l:
                on = width // bits(other)
                w(f'    simdExpect(a.as{cap(other)}x{on}().bytes(), "{encode(l, a)}")')
        w(f'    simdExpect({t}Load("xx" + a.bytes() + "yy", 2).bytes(), "{encode(l, a)}")')
        if width == 256:
            half = n // 2
            w(f'    simdExpect(a.low().bytes(), "{encode(l, a[:half])}")')
            w(f'    simdExpect(a.high().bytes(), "{encode(l, a[half:])}")')
            w(f'    simdExpect({t}Concat(a.high(), a.low()).bytes(), "{encode(l, a[half:] + a[:half])}")')
        w("}")
        w("")

w("""// What crosses a boxed boundary comes back the same: a field, an array, a closure, a
// generic and a var over a loop, and a non-inlined call in release and --fast alike.
class SimdHolder(var value: u32x4, val wide: f64x4)

class SimdBox<T>(val value: T)

fun <T> simdIdentity(value: T): T = value

@noinline fun simdPass(a: u32x4, b: u32x8, c: f32x4): u32x8 = b + u32x8Concat(a, c.asU32x4())

@noinline fun simdBoxed(): void {
    val a = u32x4(1, 2, 3, 4)
    val holder = SimdHolder(a, f64x4(1.0, 2.0, 3.0, 4.0))
    holder.value = holder.value + a
    simdExpect(holder.value.bytes(), "02000000040000000600000008000000")
    simdTrue(holder.wide.get(3) == 4.0)
    val list: array<u32x4> = [a]
    list.append(a + a)
    simdExpect(list[1].bytes(), "02000000040000000600000008000000")
    val add: (u32x4) -> u32x4 = { x: u32x4 -> x + a }
    simdExpect(add(a).bytes(), "02000000040000000600000008000000")
    simdExpect(simdIdentity(a).bytes(), "01000000020000000300000004000000")
    simdExpect(SimdBox(a).value.bytes(), "01000000020000000300000004000000")
    var total = u32x4Splat(0)
    for (i in 0 until 1000) total = total + a
    simdExpect(total.bytes(), "e8030000d00700" + "00b80b0000a00f0000")
    val wide = simdPass(a, u32x8Splat(1), f32x4Splat(0.0))
    simdExpect(wide.low().bytes(), "02000000030000000400000005000000")
    simdExpect(wide.high().bytes(), "01000000010000000100000001000000")
}

// NaN: comparisons are false but for ne, and min and max give NaN.
@noinline fun simdNaN(): void {
    val nan = f32FromBits(u32(2143289344))
    val a = f32x4(nan, 1.0, 2.0, 3.0)
    val b = f32x4Splat(1.0)
    simdTrue(a.eq(a).get(0) == u32(0))
    simdTrue(a.ne(a).get(0) == u32(4294967295))
    simdTrue(a.lt(b).get(0) == u32(0))
    simdTrue(a.min(b).get(0) != a.min(b).get(0))
    simdTrue(a.max(b).get(0) != a.max(b).get(0))
    // Saturating, as f32ToI32 is; NaN gives 0.
    val big = f32x4(nan, 3000000000.0, -3000000000.0, 1.5).toI32x4()
    simdExpect(big.bytes(), "00000000ffffff7f0000008001000000")
}

// 0 if everything agrees, or the number of the first check that doesn't.
fun simdChecks(): int {""")
for c in calls:
    w(f"    {c}()")
w("""    simdBoxed()
    simdNaN()
    simdFailure
}
""")
path = pathlib.Path(__file__).resolve().parents[2] / "tests/cases/simd/checks.ab"
path.write_text("\n".join(out))
