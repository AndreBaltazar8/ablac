#!/usr/bin/env python3
"""Writes stdlib/abla/simd/entry.ab: the same surface for each vector type, which only
differs by lane type and count. Run it after changing the surface and commit its output;
nothing runs it at build time."""
import pathlib

LANES = ["i8", "i16", "i32", "i64", "u8", "u16", "u32", "u64", "f32", "f64"]
WIDTHS = [128, 256]
BITS = {"8": 8, "16": 16, "32": 32, "64": 64}


def bits(lane): return BITS[lane[1:]]
def isfloat(lane): return lane[0] == "f"
def cap(name): return name[0].upper() + name[1:]


TYPES = [(f"{l}x{w // bits(l)}", l, w // bits(l), w) for w in WIDTHS for l in LANES]
out = []
w = out.append

w('''// Fixed-width vectors, lowered to LLVM vectors (docs/simd.md, docs/stdlib/simd.md).
// Generated by tools/simd/gen-stdlib.py; change that and run it again.

import "abla/float"
import "abla/float/text"
import "abla/process/exit"
import "abla/unsafe/memory"
export import "abla/simd/target"
''')


def ext(name, params, result="", trusted=False):
    r = f": {result}" if result else ""
    w(f'{"trusted " if trusted else ""}noescape extern:"intrinsic" fun {name}({params}){r}')


for t, l, n, width in TYPES:
    m = f"u{bits(l)}x{n}"
    p = lambda op: f"ablaSimd_{op}_{t}"
    names = [f"l{i}" for i in range(n)]
    w(f"// --- {t} " + "-" * 60)
    ext(p("make"), ", ".join(f"{a}: {l}" for a in names), t)
    ext(p("splat"), f"value: {l}", t)
    ext(p("get"), f"v: {t}, index: int", l)
    ext(p("with"), f"v: {t}, index: int, value: {l}", t)
    ext(p("bytes"), f"v: {t}", "string")
    ext(p("load"), "address: int", t, trusted=True)
    ext(p("store"), f"address: int, v: {t}", "void", trusted=True)
    w(f"@inline fun {t}({', '.join(f'{a}: {l}' for a in names)}): {t} = {p('make')}({', '.join(names)})")
    w(f"@inline fun {t}Splat(value: {l}): {t} = {p('splat')}(value)")
    w(f'''@inline fun {t}.get(index: int): {l} {{
    if (index < 0 || index >= {n}) panic("{t}: no lane $index")
    {p('get')}(this, index)
}}
@inline fun {t}.with(index: int, value: {l}): {t} {{
    if (index < 0 || index >= {n}) panic("{t}: no lane $index")
    {p('with')}(this, index, value)
}}
fun {t}Load(data: string, offset: int = 0): {t} {{
    if (offset < 0 || offset > data.size - {width // 8}) panic("{t}Load: offset $offset in ${{data.size}} bytes")
    {t}LoadAddress(nativeStringDataAddress(data) + offset)
}}
trusted fun {t}LoadAddress(address: int): {t} = {p('load')}(address)
trusted fun {t}.storeAddress(address: int): void = {p('store')}(address, this)
@inline fun {t}.bytes(): string = {p('bytes')}(this)
fun {t}.text(): string {{
    var text = "["
    for (lane in 0 until {n}) {{
        if (lane > 0) text = text + ", "
        text = text + {'f64Text(f32ToF64(this.get(lane)))' if l == 'f32' else 'f64Text(this.get(lane))' if l == 'f64' else '"${this.get(lane)}"'}
    }}
    text + "]"
}}''')
    ext(f"{t}Shuffle", f"a: {t}, b: {t}, " + ", ".join(f"i{i}: int" for i in range(n)), t)
    half = n // 2
    w(f"@inline fun {t}.interleaveLow(other: {t}): {t} = {t}Shuffle(this, other, " + ", ".join(f"{i // 2 + (n if i % 2 else 0)}" for i in range(n)) + ")")
    w(f"@inline fun {t}.interleaveHigh(other: {t}): {t} = {t}Shuffle(this, other, " + ", ".join(f"{half + i // 2 + (n if i % 2 else 0)}" for i in range(n)) + ")")
    w(f"@inline fun {t}.reverse(): {t} = {t}Shuffle(this, this, " + ", ".join(str(n - 1 - i) for i in range(n)) + ")")
    for op, oper in [("add", "plus"), ("sub", "minus"), ("mul", "times")] + ([("div", "div")] if isfloat(l) else []):
        ext(p(op), f"a: {t}, b: {t}", t)
        w(f"@inline operator fun {t}.{oper}(other: {t}): {t} = {p(op)}(this, other)")
    ext(p("neg"), f"a: {t}", t)
    w(f"@inline operator fun {t}.unaryMinus(): {t} = {p('neg')}(this)")
    for op in ["min", "max"]:
        ext(p(op), f"a: {t}, b: {t}", t)
        w(f"@inline fun {t}.{op}(other: {t}): {t} = {p(op)}(this, other)")
    if l[0] != "u":
        ext(p("abs"), f"a: {t}", t)
        w(f"@inline fun {t}.abs(): {t} = {p('abs')}(this)")
    if isfloat(l):
        ext(p("sqrt"), f"a: {t}", t)
        w(f"@inline fun {t}.sqrt(): {t} = {p('sqrt')}(this)")
    else:
        for op in ["and", "or", "xor"]:
            ext(p(op), f"a: {t}, b: {t}", t)
            w(f"@inline operator fun {t}.{op}(other: {t}): {t} = {p(op)}(this, other)")
        ext(p("not"), f"a: {t}", t)
        w(f"@inline operator fun {t}.inv(): {t} = {p('not')}(this)")
        w(f"@inline fun {t}.andNot(other: {t}): {t} = {p('and')}(this, {p('not')}(other))")
        for op in ["addSat", "subSat"]:
            ext(p(op), f"a: {t}, b: {t}", t)
            w(f"@inline fun {t}.{op}(other: {t}): {t} = {p(op)}(this, other)")
        for op, oper in [("shl", "shl"), ("shr", "shr")]:
            ext(p(op), f"a: {t}, count: int", t)
            w(f"@inline operator fun {t}.{oper}(count: int): {t} = {p(op)}(this, count)")
        for op in ["rotl", "rotr"]:
            ext(p(op), f"a: {t}, count: int", t)
            w(f"@inline fun {t}.{op}(count: int): {t} = {p(op)}(this, count)")
    for op in ["eq", "ne", "lt", "le", "gt", "ge"]:
        ext(p(op), f"a: {t}, b: {t}", m)
        w(f"@inline fun {t}.{op}(other: {t}): {m} = {p(op)}(this, other)")
    ext(p("select"), f"mask: {m}, a: {t}, b: {t}", t)
    w(f"@inline fun {m}.select(a: {t}, b: {t}): {t} = {p('select')}(this, a, b)")
    ext(p("bitmask"), f"a: {t}", "int")
    w(f"@inline fun {t}.bitmask(): int = {p('bitmask')}(this)")
    if not isfloat(l) and l[0] == "u":
        w(f"@inline fun {t}.any(): bool = {p('bitmask')}(this) != 0")
        w(f"@inline fun {t}.all(): bool = {p('bitmask')}(this) == {(1 << n) - 1}")
    ext(p("sum"), f"a: {t}", l)
    w(f"@inline fun {t}.sum(): {l} = {p('sum')}(this)")
    for u, ul, un, uw in TYPES:
        if uw == width and u != t:
            name = f"ablaSimd_bits_{t}_{u}"
            ext(name, f"a: {t}", u)
            w(f"@inline fun {t}.as{cap(u)}(): {u} = {name}(this)")
    if isfloat(l):
        for target in [f"i{bits(l)}x{n}", f"u{bits(l)}x{n}"]:
            name = f"ablaSimd_convert_{t}_{target}"
            ext(name, f"a: {t}", target)
            w(f"@inline fun {t}.to{cap(target)}(): {target} = {name}(this)")
    elif bits(l) >= 32:
        target = f"f{bits(l)}x{n}"
        name = f"ablaSimd_convert_{t}_{target}"
        ext(name, f"a: {t}", target)
        w(f"@inline fun {t}.to{cap(target)}(): {target} = {name}(this)")
    if width == 256:
        half_t = f"{l}x{n // 2}"
        for op in ["low", "high"]:
            ext(p(op), f"a: {t}", half_t)
            w(f"@inline fun {t}.{op}(): {half_t} = {p(op)}(this)")
    else:
        double = f"{l}x{n * 2}"
        ext(p("concat"), f"low: {t}, high: {t}", double)
        w(f"@inline fun {double}Concat(low: {t}, high: {t}): {double} = {p('concat')}(low, high)")
    w("")

w('''// --- Target-specific operations (docs/simd.md) -----------------------------------
// Only under @target and a cpuHas check: the compiler refuses them elsewhere, and a
// target without the instruction traps here.

/** One AES encryption round: ShiftRows, SubBytes, MixColumns, then XOR the round key. */
noescape extern:"intrinsic" fun aesEncRound(state: u8x16, roundKey: u8x16): u8x16
/** The last encryption round: no MixColumns. */
noescape extern:"intrinsic" fun aesEncLastRound(state: u8x16, roundKey: u8x16): u8x16
/** One AES decryption round, as x86's AESDEC: the key is the equivalent inverse cipher's. */
noescape extern:"intrinsic" fun aesDecRound(state: u8x16, roundKey: u8x16): u8x16
noescape extern:"intrinsic" fun aesDecLastRound(state: u8x16, roundKey: u8x16): u8x16
/** InvMixColumns, to turn an encryption round key into a decryption one. */
noescape extern:"intrinsic" fun aesInvMixColumns(state: u8x16): u8x16
/** Carry-less product of one 64-bit lane of each: `selector` (a literal) picks a's lane
 *  with bit 0 and b's with bit 4, as PCLMULQDQ does. */
noescape extern:"intrinsic" fun clmul(a: u64x2, b: u64x2, selector: int): u64x2
''')

path = pathlib.Path(__file__).resolve().parents[2] / "stdlib/abla/simd/entry.ab"
path.parent.mkdir(parents=True, exist_ok=True)
path.write_text("\n".join(out))
