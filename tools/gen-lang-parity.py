#!/usr/bin/env python3
"""Writes tests/cases/lang-parity/*.ab: each area's body is compiled twice, as an
ordinary function and as a `compile fun`, and the strings the two return must match
(the second is evaluated under `#`). Native operands go through non-inlined identities
so the program's own lowering runs instead of the builder's constant folding.
Regenerate with: python3 tools/gen-lang-parity.py (then commit the output).

A body is a list of lines using `out.append(...)`; `o("string", '"x"')` marks an operand
that is opaque on the native side only; `@` in a call becomes N or C."""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "tests", "cases", "lang-parity")

OPAQUE = re.compile("\x01([A-Za-z0-9_]+)\x02(.*?)\x03", re.S)
IDENTITIES = {
    "string": "string", "int": "int", "bool": "bool", "f64": "f64", "ints": "array<int>",
    "strings": "array<string>",
}


def o(kind, text):
    return f"\x01{kind}\x02{text}\x03"


def side(text, native):
    return OPAQUE.sub((lambda m: f"id_{m.group(1)}({m.group(2)})") if native
                      else (lambda m: m.group(2)), text)


def write(name, declarations, helpers, imports=()):
    """helpers: list of (case name, body lines); each returns array<string>."""
    lines = [f"// Generated by tools/gen-lang-parity.py: {name}.",
             "// Each case runs as ordinary code and under `#`; the strings must match.",
             'import "abla/io"']
    lines += [f'import "{i}"' for i in imports]
    lines.append("")
    for kind, type_ in IDENTITIES.items():
        lines.append(f"@noinline fun id_{kind}(x: {type_}): {type_} = x")
    lines.append("")
    lines += declarations
    lines.append("")
    for kind in ("fun", "compile fun"):
        suffix = "N" if kind == "fun" else "C"
        for case, body in helpers:
            lines.append(f"{kind} {case}{suffix}(): array<string> {{")
            lines.append("    val out: array<string> = []")
            lines += ["    " + side(line, kind == "fun").replace("@", suffix) for line in body]
            lines.append("    out")
            lines.append("}")
            lines.append("")
    lines += [
        "fun report(name: string, native: array<string>, staged: array<string>): int {",
        "    var bad = 0",
        "    if (native.size != staged.size) {",
        '        println("${name}: sizes ${native.size} ${staged.size}")',
        "        bad = 1000000",
        "    }",
        "    var i = 0",
        "    while (i < native.size && i < staged.size) {",
        "        if (native[i] != staged[i]) {",
        "            bad = bad + 1",
        '            if (bad <= 5) println("${name}[${i}]\\nnative: ${native[i]}\\nstaged: ${staged[i]}")',
        "        }",
        "        i = i + 1",
        "    }",
        "    bad",
        "}",
        "",
        "fun main: int {",
        "    var bad = 0"]
    for case, _ in helpers:
        lines.append(f'    bad = bad + report("{case}", {case}N(), #{case}C())')
    lines += ["    if (bad == 0) 42 else 1", "}", ""]
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name + ".ab"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


