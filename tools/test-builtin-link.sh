#!/usr/bin/env bash
# The libc-free links without clang (src/toolchain.ab, bootstrapBuiltinLinkArguments): the ld.lld command line is built by the compiler for the x86-64 and AArch64 Linux
# static-pie links, and a toolchain's own compiler-rt builtins archive replaces asking clang for its path. Held to the driver's: every program built both ways (the
# builtin command, and ABLA_LINK_BUILTIN=0 which asks clang for the command, in a cache of its own) is byte for byte the same executable, for x86-64 and AArch64; and a
# build with a PATH that has no clang (ld.lld and the coreutils the compiler runs) and ABLA_COMPILER_RT_BUILTINS naming the archive builds and runs a program.
# Usage: tools/test-builtin-link.sh [compiler]
set -euo pipefail
export LC_ALL=C
compiler=${1:-build/ablac}
[[ $compiler == /* || $compiler != */* ]] || compiler="$PWD/$compiler"
root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
cd "$root"
[[ $(uname -s) == Linux ]] || { echo 'builtin link: Linux only'; exit 0; }
unset ABLA_DEBUG ABLA_TEST_FAST_BUILDS ABLA_LINK_DIRECT ABLA_LINK_BUILTIN ABLA_COMPILER_RT_BUILTINS
export ABLA_SYSROOT=${ABLA_SYSROOT:-$root}
out=build/builtin-link
rm -rf "$out"
mkdir -p "$out"
fail() { echo "builtin link: $*" >&2; exit 1; }
programs=(tests/cases/libc-imports/hello.ab tests/cases/libc-imports/strings-arrays.ab tests/cases/libc-imports/files.ab tests/cases/libc-imports/tasks.ab
    tests/cases/libc-imports/threads.ab tests/cases/libc-imports/float-remainder.ab tests/cases/modules/http-event.ab tests/cases/modules/udp-ephemeral.ab)
count=0
for program in "${programs[@]}"; do
    name=$(basename -- "$program" .ab)
    for variant in "x86:" "x86-release:" "aarch64:--target aarch64-linux"; do
        tag=${variant%%:*}
        read -r -a flags <<< "${variant#*:}"
        fast=(--fast)
        [[ $tag == x86-release ]] && fast=()
        ABLA_CACHE_DIR=$PWD/$out/$name.$tag.builtin.cache "$compiler" build "$program" -o "$out/$name.$tag.builtin" "${fast[@]}" "${flags[@]}" > "$out/$name.$tag.builtin.log" 2>&1 ||
            { tail -5 "$out/$name.$tag.builtin.log" >&2; fail "$name ($tag): the build with the builtin command failed"; }
        ABLA_LINK_BUILTIN=0 ABLA_CACHE_DIR=$PWD/$out/$name.$tag.clang.cache "$compiler" build "$program" -o "$out/$name.$tag.clang" "${fast[@]}" "${flags[@]}" > "$out/$name.$tag.clang.log" 2>&1 ||
            { tail -5 "$out/$name.$tag.clang.log" >&2; fail "$name ($tag): the build asking clang failed"; }
        cmp -s "$out/$name.$tag.builtin" "$out/$name.$tag.clang" || fail "$name ($tag): the builtin link differs from clang's"
        # the link the builtin build ran left no kept clang command in its cache: nothing asked clang for one
        kept=$(ls "$out/$name.$tag.builtin.cache"/link 2> /dev/null | grep -v runtime-library || true)
        [[ -z $kept ]] || fail "$name ($tag): the builtin build asked clang for a link command"
        count=$((count + 1))
    done
done
# No clang on the PATH: ld.lld, the coreutils the compiler runs and the builtins archive named. x86-64 and AArch64.
builtins=$(clang --rtlib=compiler-rt -print-libgcc-file-name)
[[ -f $builtins ]] || fail "no compiler-rt builtins archive to name"
bin=$out/bin
mkdir -p "$bin"
# (a cross target is still generated by the external opt, llc and llvm-extract, which the AArch64 build below needs; the link itself asks no clang)
for tool in ld.lld env cp nproc rm mktemp cat uname dirname readlink opt llc llvm-extract llvm-ar; do
    path=$(command -v "$tool" 2> /dev/null || true)
    [[ -z $path ]] || ln -sf "$path" "$bin/$tool"
done
[[ ! -e $bin/clang ]] || fail "clang is in the test's PATH"
# (the launcher is a script that needs more of a PATH than the compiler does: the compiler itself runs)
raw=$compiler
[[ -x $(dirname -- "$compiler")/ablac.bin ]] && raw=$(dirname -- "$compiler")/ablac.bin
for variant in "x86:" "aarch64:--target aarch64-linux"; do
    tag=${variant%%:*}
    read -r -a flags <<< "${variant#*:}"
    PATH=$PWD/$bin ABLA_COMPILER_RT_BUILTINS=$builtins ABLA_CACHE_DIR=$PWD/$out/noclang.$tag.cache "$raw" build tests/cases/libc-imports/hello.ab -o "$out/noclang.$tag" --fast "${flags[@]}" \
        > "$out/noclang.$tag.log" 2>&1 || { tail -5 "$out/noclang.$tag.log" >&2; fail "hello ($tag) did not build without clang on the PATH"; }
    cmp -s "$out/noclang.$tag" "$out/hello.$tag.clang" || fail "hello ($tag) built without clang differs from the one built with it"
done
[[ $("$out/noclang.x86") == hello ]] || fail "the clang-free x86-64 hello did not print hello"
echo "builtin link: $count builds (${#programs[@]} programs x 3 ways) identical to the ones that ask clang for the command; hello builds, byte for byte the same, with no clang on the PATH (x86-64 and AArch64)"
