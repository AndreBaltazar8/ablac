#!/usr/bin/env python3
"""Cases for abla/uint256, worked out with Python's integers: edge values against each other,
then random ones of every length. tests/cases/uint256/checks.ab runs them on each target.

gen-cases.py SEED COUNT            lines of `operation a b expected`, in hex unless noted
gen-cases.py SEED COUNT --abla     the same as an Abla module holding them in UINT256_CASES
"""
import random
import sys

M = 1 << 256
TOP = M - 1

EDGES = sorted({0, 1, 2, 3, 5, 9, 10, 255, 256, TOP, TOP - 1, TOP // 2, TOP // 2 + 1, TOP // 10, TOP // 10 + 1,
                10 ** 9, 10 ** 18, 10 ** 19, 10 ** 77, 1 << 128, (1 << 128) - 1, (1 << 128) + 1,
                0xFFFFFFFF, 0xFFFFFFFF << 224, int("AA" * 32, 16), int("55" * 32, 16),
                int("0123456789abcdef" * 4, 16), 2 ** 63 - 1, 2 ** 63, 2 ** 64 - 1, 2 ** 64, 2 ** 32, 2 ** 16, 2 ** 8}
               | {1 << k for k in range(32, 256, 32)} | {(1 << k) - 1 for k in range(32, 256, 32)})
SHIFTS = [0, 1, 4, 31, 32, 33, 63, 64, 65, 127, 128, 129, 200, 255, 256, 257, 1000]
BAD_DECIMAL = ["", "-1", "+1", " 1", "1 ", "1.5", "1e3", "0x10", "a", str(M), str(M + 5), str(10 ** 78), "9" * 100]
BAD_HEX = ["", "0x", "0X", "g", "0xg", " 0x1", "0x 1", "-1", "0x" + "1" + "0" * 64, "F" * 65]


def hexed(value):
    return f"{value:x}"


def checked(value):
    return hexed(value) if 0 <= value < M else "n"


def narrowed(value, bits):
    return hexed(value) if value < (1 << bits) else "n"


def pair_lines(a, b):
    x, y = hexed(a), hexed(b)
    yield f"add {x} {y} {hexed((a + b) % M)}"
    yield f"sub {x} {y} {hexed((a - b) % M)}"
    yield f"mul {x} {y} {hexed((a * b) % M)}"
    if b:
        yield f"div {x} {y} {hexed(a // b)}"
        yield f"rem {x} {y} {hexed(a % b)}"
    yield f"and {x} {y} {hexed(a & b)}"
    yield f"or {x} {y} {hexed(a | b)}"
    yield f"xor {x} {y} {hexed(a ^ b)}"
    yield f"lt {x} {y} {int(a < b)}"
    yield f"le {x} {y} {int(a <= b)}"
    yield f"gt {x} {y} {int(a > b)}"
    yield f"ge {x} {y} {int(a >= b)}"
    yield f"eq {x} {y} {int(a == b)}"
    yield f"ne {x} {y} {int(a != b)}"
    yield f"addc {x} {y} {checked(a + b)}"
    yield f"subc {x} {y} {checked(a - b)}"
    yield f"mulc {x} {y} {checked(a * b)}"


def one_lines(a, rng):
    x = hexed(a)
    yield f"not {x} 0 {hexed(TOP ^ a)}"
    yield f"neg {x} 0 {hexed(-a % M)}"
    yield f"dec {x} 0 {a}"
    yield f"decp {a} 0 {x}"
    yield f"decp {'0' * rng.randrange(4)}{a} 0 {x}"
    yield f"hexs {x} 0 0x{x}"
    yield f"hexp 0x{x} 0 {x}"
    yield f"hexp {x.upper()} 0 {x}"
    yield f"bytes {x} 0 {a.to_bytes(32, 'big').hex()}"
    length = rng.randrange((a.bit_length() + 7) // 8, 33) if a else rng.randrange(33)
    if length:
        yield f"bytesp {a.to_bytes(length, 'big').hex()} 0 {x}"
    yield f"bits {x} 0 {a.bit_length()}"
    index = rng.randrange(256)
    yield f"bit {x} {index:x} {(a >> index) & 1}"
    yield f"u64n {x} 0 {narrowed(a, 64)}"
    yield f"intn {x} 0 {narrowed(a, 63)}"
    yield f"u32n {x} 0 {narrowed(a, 32)}"
    yield f"u16n {x} 0 {narrowed(a, 16)}"
    yield f"u8n {x} 0 {narrowed(a, 8)}"
    yield f"u64 {x} 0 {hexed(a & (2 ** 64 - 1))}"
    yield f"u32 {x} 0 {hexed(a & (2 ** 32 - 1))}"
    yield f"u16 {x} 0 {hexed(a & 65535)}"
    yield f"u8 {x} 0 {hexed(a & 255)}"
    low = a & (2 ** 64 - 1)
    yield f"sext {hexed(low)} 0 {hexed(low if low < 2 ** 63 else low - 2 ** 64 + M)}"
    yield f"zext {hexed(low)} 0 {hexed(low)}"


def shift_lines(a, count):
    x = hexed(a)
    yield f"shl {x} {count:x} {hexed((a << count) % M)}"
    yield f"shr {x} {count:x} {hexed(a >> count)}"
    yield f"shlw {x} {count:x} {hexed((a << count) % M)}"
    yield f"shrw {x} {count:x} {hexed(a >> count)}"


def lines(seed, count):
    rng = random.Random(seed)
    out = []
    for text in BAD_DECIMAL:
        out.append(f"decp {text.replace(' ', '_') or '_'} 0 n")
    for text in BAD_HEX:
        out.append(f"hexp {text.replace(' ', '_') or '_'} 0 n")
    out.append("bytesp " + "01" * 33 + " 0 n")
    edges = EDGES[:]
    for a in edges:
        out.extend(one_lines(a, rng))
        for count_ in SHIFTS:
            out.extend(shift_lines(a, count_))
    for a in edges:
        for b in rng.sample(edges, 12):
            out.extend(pair_lines(a, b))
    while len(out) < count:
        a = rng.getrandbits(rng.randrange(257))
        b = rng.getrandbits(rng.randrange(257)) if rng.randrange(4) else rng.choice(edges)
        out.extend(pair_lines(a, b))
        out.extend(one_lines(a, rng))
        out.extend(shift_lines(a, rng.choice(SHIFTS + [rng.randrange(256)])))
    return out


def main():
    seed, count = int(sys.argv[1]), int(sys.argv[2])
    cases = lines(seed, count)
    if "--abla" in sys.argv[3:]:
        print("// Generated by tools/uint256/gen-cases.py.")
        print('val UINT256_CASES = "' + "\\n".join(cases) + '\\n"')
    else:
        print("\n".join(cases))


main()
