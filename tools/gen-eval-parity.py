#!/usr/bin/env python3
"""Writes tests/cases/eval-parity/*.ab: each case is computed by ordinary code
and again under `#`, and the two strings are compared. One area per file.
Regenerate with: python3 tools/gen-eval-parity.py (then commit the output)."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "tests", "cases", "eval-parity")
CHUNK = 60

INTS = [("i8", 8, True), ("i16", 16, True), ("i32", 32, True), ("int", 64, True),
        ("u8", 8, False), ("u16", 16, False), ("u32", 32, False), ("u64", 64, False)]
I64_MIN = "(-9223372036854775807 - 1)"


def lit(value, ty):
    """A literal of `ty` holding `value` (a u64 beyond int range is its two's complement)."""
    if ty == "u64" and value >= 2 ** 63:
        value -= 2 ** 64
    text = I64_MIN if value == -2 ** 63 else (f"({value})" if value < 0 else str(value))
    return text if ty == "int" else f"{ty}({text})"


def edges(ty, bits, signed):
    low, high = (-(2 ** (bits - 1)), 2 ** (bits - 1) - 1) if signed else (0, 2 ** bits - 1)
    values = [low, low + 1, -2, -1, 0, 1, 2, 7, 100, high - 1, high, high // 2 + 1]
    seen = []
    for v in values:
        if low <= v <= high and v not in seen:
            seen.append(v)
    return seen


def write(name, cases, imports=(), helpers=()):
    """cases: list of (label, expression) pairs; `@` in an expression becomes the
    side's suffix (N native, C staged). helpers: (name, result type, body lines), each
    emitted per side as <name><suffix>()."""
    chunks = [cases[i:i + CHUNK] for i in range(0, len(cases), CHUNK)]
    lines = [f"// Generated by tools/gen-eval-parity.py: {name}, {len(cases)} cases.",
             "// Each is computed natively and under `#`; the strings must match.",
             'import "abla/io"', 'import "abla/float"']
    lines += [f'import "{i}"' for i in imports]
    lines.append("")
    for kind in ("fun", "compile fun"):
        suffix = "N" if kind == "fun" else "C"
        for helper, result, body in helpers:
            lines.append(f"{kind} {helper}{suffix}(): {result} {{")
            lines += ["    " + line for line in body]
            lines.append("}")
            lines.append("")
        for index, chunk in enumerate(chunks):
            lines.append(f"{kind} chunk{suffix}{index}(): array<string> {{")
            lines.append("    val out: array<string> = []")
            for label, expression in chunk:
                lines.append(f'    out.append("{label} = ${{{expression.replace("@", suffix)}}}")')
            lines.append("    out")
            lines.append("}")
            lines.append("")
        lines.append(f"{kind} all{suffix}(): array<string> {{")
        lines.append("    val out: array<string> = []")
        for index in range(len(chunks)):
            lines.append(f"    for (s in chunk{suffix}{index}()) out.append(s)")
        lines.append("    out")
        lines.append("}")
        lines.append("")
    lines += [
        "fun main: int {",
        "    val native = allN()",
        "    val staged = #allC()",
        "    var bad = 0",
        "    if (native.size != staged.size) bad = 1000000",
        "    var index = 0",
        "    while (index < native.size && index < staged.size) {",
        "        if (native[index] != staged[index]) {",
        "            bad = bad + 1",
        '            if (bad <= 10) println("native: ${native[index]}\\nstaged: ${staged[index]}")',
        "        }",
        "        index = index + 1",
        "    }",
        "    if (bad == 0) 42 else 1",
        "}",
        ""]
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name + ".ab"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def binary(op, ty, bits, signed, pairs=None, skip_zero=False):
    cases = []
    values = edges(ty, bits, signed)
    for a in values:
        for b in values:
            if skip_zero and b == 0:
                continue
            cases.append((f"{ty} {a} {op} {b}", f"{lit(a, ty)} {op} {lit(b, ty)}"))
    return cases


def main():
    arithmetic, divrem, bitwise, compare, shifts, unary, convert = [], [], [], [], [], [], []
    for ty, bits, signed in INTS:
        for op in ("+", "-", "*"):
            arithmetic += binary(op, ty, bits, signed)
        for op in ("/", "%"):
            divrem += binary(op, ty, bits, signed, skip_zero=True)
        for op in ("&", "|", "^"):
            bitwise += binary(op, ty, bits, signed)
        for op in ("<", "<=", ">", ">=", "==", "!="):
            compare += binary(op, ty, bits, signed)
        values = edges(ty, bits, signed)
        counts = sorted({0, 1, 2, bits - 1, bits, bits + 1, 63, 64, 65, 100})
        if signed:
            counts += [-1, -bits]
        counts = [c for c in counts if (-(2 ** (bits - 1)) <= c <= 2 ** (bits - 1) - 1 if signed
                                        else 0 <= c <= 2 ** bits - 1)]
        for op in ("<<", ">>", ">>>"):
            for a in values:
                for c in counts:
                    shifts.append((f"{ty} {a} {op} {c}", f"{lit(a, ty)} {op} {lit(c, ty)}"))
        if signed:
            for a in values:
                unary.append((f"{ty} -{a}", f"-{lit(a, ty)}"))
        for a in values:
            unary.append((f"{ty} ~{a}", f"~{lit(a, ty)}"))
        for dst, dbits, dsigned in INTS:
            for a in values:
                convert.append((f"{dst}({ty} {a})", f"{dst}({lit(a, ty)})"))
    write("integer-arithmetic", arithmetic + unary)
    write("integer-division", divrem)
    write("integer-bitwise", bitwise + compare)
    write("integer-shifts", shifts)
    write("integer-conversions", convert)

    # Loops and compound assignment wrap at every width.
    mixed, helpers = [], []
    for ty, bits, signed in INTS:
        values = edges(ty, bits, signed)
        helper = f"loop_{ty}"
        body = [f"var v = {lit(values[0], ty)}", f"var w = {lit(values[-1], ty)}",
                "var i = 0", "while (i < 70) {",
                f"    v += w", f"    w *= {lit(3, ty)}", f"    v -= {lit(7, ty)}",
                f"    w = w ^ v", "    if (i % 5 == 0) v = v * v",
                "    i = i + 1", "}", '"${v} ${w}"']
        helpers.append((helper, "string", body))
        mixed.append((f"loop {ty}", f"{helper}@()"))
    write("integer-mixed", mixed, helpers=helpers)

    # Floats: f32 rounding and arithmetic, widening, saturating conversion to integers.
    f64s = ["0.0", "(-0.0)", "1.0", "0.1", "(-1.5)", "2.5", "3.0e10", "16777217.0", "16777219.0",
            "1.0e-45", "7.0e-46", "3.4028235e38", "3.4028236e38", "3.4028235677973366e38",
            "1.0e39", "(-1.0e39)", "1.00000011920928955", "1.00000005960464478",
            "1.0000000596046448", "1.0e300", "4.9e-324"]
    floats = []
    for x in f64s:
        floats.append((f"f32bits({x})", f"f32ToBits(f64ToF32({x}))"))
        floats.append((f"widen({x})", f"f64ToBits(f32ToF64(f64ToF32({x})))"))
    f32s = [f"f64ToF32({x})" for x in ["0.0", "1.0", "0.1", "(-2.5)", "16777216.0", "3.4028235e38",
                                       "1.0e-45", "1.17549435e-38", "0.3", "7.0", "(-7.0)", "2.0"]]
    for i, a in enumerate(f32s):
        for j, b in enumerate(f32s):
            for op in ("+", "-", "*", "/", "%"):
                floats.append((f"f32 #{i} {op} #{j}", f"f32ToBits({a} {op} {b})"))
            for op in ("<", "==", ">="):
                floats.append((f"f32 #{i} {op} #{j}", f"{a} {op} {b}"))
    sat = ["0.0", "(-0.5)", "0.9999999", "1.0e10", "(-1.0e10)", "2147483647.0", "2147483648.0",
           "(-2147483648.0)", "(-2147483649.0)", "4294967295.0", "4294967296.0", "(-1.0)",
           "9.3e18", "(-9.3e18)", "1.0e19", "1.0e300", "(0.0 / 0.0)", "(1.0 / 0.0)", "(-1.0 / 0.0)"]
    for x in sat:
        floats.append((f"f64ToInt({x})", f"f64ToInt({x})"))
        floats.append((f"f32ToI32({x})", f"f32ToI32(f64ToF32({x}))"))
        floats.append((f"f32ToU32({x})", f"f32ToU32(f64ToF32({x}))"))
        floats.append((f"f32ToInt({x})", f"f32ToInt(f64ToF32({x}))"))
    for v in ["0", "1", "(-1)", "16777217", "2147483647", "(-2147483647 - 1)"]:
        floats.append((f"f32FromI32({v})", f"f32ToBits(f32FromI32(i32({v})))"))
        floats.append((f"f64FromInt({v})", f"f64ToBits(f64FromInt({v}))"))
    for v in ["0", "1", "16777217", "4294967295", "4294967041"]:
        floats.append((f"f32FromU32({v})", f"f32ToBits(f32FromU32(u32({v})))"))
    # Text of floats: the shortest form that reads back.
    for x in f64s + ["123456.789", "1.5e-7", "1.0e21", "1.0e22", "0.000001", "5.0e-324",
                     "1.7976931348623157e308", "100.0", "2.0e-5", "(-0.0)", "0.30000000000000004"]:
        floats.append((f"text f64 {x}", f"{x}"))
        floats.append((f"text f32 {x}", f"f64ToF32({x})"))
    write("float-scalars", floats, imports=("abla/float/text",))


main()
